export function reasonLabel(result,language='zh'){
 if(result?.reasonCode==='HW_IMPORT_REVIEW'){
  return t('inventory.quoteReview',language,{fields:result.fields.map(key=>t('inventory.field.'+key,language)).join(', ')});
 }
 const entry=ENGINE_REASON_MESSAGES[result?.reasonCode||result?.code];
 return entry?entry[normalizeLanguage(language)==='en'?1:0]:translateMessage(result?.reason||'',language);
}
export function mappingLabel(issue,language='zh'){return t('mapping.'+issue.code,language,issue);}
export function translateMessage(value,language='zh'){
 const text=String(value??'');
 for(const entry of Object.values(ENGINE_REASON_MESSAGES))if(entry.includes(text))return entry[normalizeLanguage(language)==='en'?1:0];
 if(normalizeLanguage(language)!=='en')return text;
 if(Object.hasOwn(MODEL_MESSAGES,text))return MODEL_MESSAGES[text];
 let m=text.match(/^请为(按需|包月|包年)选择已验证的目标规格；未获取价格的服务保持 Pending。$/);
 if(m)return `Select a verified ${MODEL_MESSAGES[m[1]]} target SKU. Services without verified prices stay Pending.`;
 m=text.match(/^第 (\d+) 行缺少 product \/ service 列$/);if(m)return `Row ${m[1]} is missing a product / service column.`;
 m=text.match(/^(.+) 不能为空$/);if(m)return `${FIELDS[m[1]]||m[1]} is required.`;
 m=text.match(/^(.+) 必须是 0–10¹² 的有限数字$/);if(m)return `${FIELDS[m[1]]||m[1]} must be a finite number between 0 and 10¹².`;
 return text;
}
export function applyTranslations(root,language){
 root.querySelectorAll('[data-i18n]').forEach(element=>{element.textContent=t(element.dataset.i18n,language);});
 for(const [attribute,key] of [['placeholder','i18nPlaceholder'],['aria-label','i18nAria'],['title','i18nTitle']]){
  root.querySelectorAll(`[data-${key.replace(/[A-Z]/g,c=>'-'+c.toLowerCase())}]`).forEach(element=>element.setAttribute(attribute,t(element.dataset[key],language)));
 }
}
